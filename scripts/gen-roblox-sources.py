#!/usr/bin/env python3
"""Bundle roblox/src into a Luau table so tests can load the real glue code.

Why this exists. The standalone `luau` CLI has no `io` library, so a test cannot
read a .luau file off disk. Every test in this repo therefore loaded only the
pure modules in src/shared through the CLI's own `require`, and the code that
actually runs in Roblox -- World.luau, init.server.luau, init.client.luau -- was
never executed. The suite passed 353/353 while the game was unplayable.

This writes every source file into one Luau module as path -> source text. The
shim then compiles each entry with loadstring and runs it with a `require` and a
`script` of its own, so `require(Shared.Config)` and `require(script.World)`
both resolve exactly as Rojo makes them resolve in the real place.

The output is regenerated by scripts/test-roblox.sh before the runtime tests run,
so it can never go stale: a source edit is picked up on the next test run rather
than being tested against a stale copy.

Usage:
    python3 scripts/gen-roblox-sources.py [output-path] [--src DIR]

`--src` defaults to roblox/src. AX Garden Legends passes roblox-garden/src, so
each game gets its own bundle and one game's sources can never leak into the
other's runtime tests.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(ROOT, "roblox", "src")
DEFAULT_OUT = os.path.join(ROOT, "roblox", "tests", ".generated", "Sources.luau")

# Set from the command line before collect() runs.
SRC = DEFAULT_SRC


def collect() -> "list[tuple[str, str]]":
    """Every .luau under roblox/src, as (logical path, source).

    The logical path is the one the shim's require understands: relative to
    roblox/src and without the extension, e.g. "shared/Config" or "server/World".
    """
    out = []
    for dirpath, dirnames, filenames in os.walk(SRC):
        dirnames.sort()
        for name in sorted(filenames):
            if not name.endswith(".luau"):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, SRC).replace(os.sep, "/")
            logical = rel[: -len(".luau")]
            with open(full, encoding="utf-8") as fh:
                out.append((logical, fh.read()))
    return out


def lua_long_string(text: str) -> str:
    """Wrap source in a Luau long string, picking a level the text cannot close.

    A long string ends at the first matching `]==]`, so the level has to be one
    the body does not contain. Source that itself contains `]]` (a nested long
    string) is common here, so this escalates until it is safe.
    """
    level = 0
    while True:
        close = "]" + "=" * level + "]"
        if close not in text:
            break
        level += 1
    open_ = "[" + "=" * level + "["
    # A leading newline is dropped by Luau long strings; keep the body exact by
    # only using the long-string form when it round-trips, else fall back.
    return open_ + "\n" + text + close


def render(files) -> str:
    lines = [
        "--!nocheck",
        "-- GENERATED by scripts/gen-roblox-sources.py -- do not edit.",
        "--",
        "-- The real roblox/src tree, as path -> source. The runtime tests compile",
        "-- and run these through tests/RobloxShim.luau, because the standalone Luau",
        "-- CLI has no io library and so cannot read a file off disk.",
        "",
        "return {",
    ]
    for logical, source in files:
        lines.append("\t[%s] = %s," % (json.dumps(logical), lua_long_string(source)))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    global SRC
    args = [a for a in sys.argv[1:]]
    src_override = None
    if "--src" in args:
        i = args.index("--src")
        src_override = args[i + 1]
        del args[i : i + 2]
    out = args[0] if args else DEFAULT_OUT
    if src_override:
        SRC = src_override if os.path.isabs(src_override) else os.path.join(ROOT, src_override)

    files = collect()
    if not files:
        print("GEN_ROBLOX_SOURCES=FAIL reason=no_files_found", file=sys.stderr)
        return 2
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(render(files))
    print("GEN_ROBLOX_SOURCES=OK files=%d out=%s" % (len(files), out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
