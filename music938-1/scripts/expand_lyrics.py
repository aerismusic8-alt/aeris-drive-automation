def _rebuild(text: str, verse_add, chorus_add, bridge_add) -> str:
    lines = text.splitlines()
    # Split into (header_lines, [(section, [content_lines])])
    header, sections, cur = [], [], None
    for raw in lines:
        s = raw.strip()
        if s.startswith("[") and s.endswith("]"):
            cur = (s[1:-1].strip().lower(), [])
            sections.append(cur)
        elif s.startswith("#") or not sections:
            header.append(raw)
        else:
            cur[1].append(raw)

    out = list(header)
    verse_i = 0
    for name, body in sections:
        out.append("")
        out.append(f"[{name}]")
        out.extend(body)
        if name == "verse":
            verse_i += 1
            if verse_i == 1:
                out.extend(verse_add)
        elif name == "chorus":
            out.extend(chorus_add)
        elif name == "bridge":
            out.extend(bridge_add)
    return "\n".join(out) + "\n"


def main() -> int:
    for slug, (v, c, b) in ADD.items():
        p = LYRICS / f"{slug}.txt"
        if not p.exists():
            print(f"MISSING {p}")
            continue
        before = p.read_text(encoding="utf-8")
        if v[0] in before:
            print(f"  {slug}: already expanded, skipped")
            continue
        p.write_text(_rebuild(before, v, c, b), encoding="utf-8")
        print(f"  {slug}: expanded")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
